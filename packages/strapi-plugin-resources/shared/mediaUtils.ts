import {
  DEFAULT_ALLOWED_DOWNLOAD_EXTENSIONS,
  DEFAULT_ALLOWED_DOWNLOAD_MIME_TYPES,
} from './constants';
import type { MediaLibraryAsset, MediaLibraryFormatVariant } from './types';

/**
 * Strips path traversal sequences (`../`, `..\\`), directory separators,
 * quotes, and control characters from a filename before use in HTTP headers.
 */
export function sanitizeFilename(rawName: unknown, fallbackExt = '.pdf'): string {
  const input = typeof rawName === 'string' ? rawName.trim() : '';
  const base = input
    .replace(/\\/g, '/')
    .split('/')
    .pop() || '';
  const cleaned = base
    .replace(/\.\.+/g, '.')
    .replace(/[^a-zA-Z0-9._-]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^[-.]+|[-.]+$/g, '')
    .slice(0, 120);

  if (!cleaned) {
    return `resource${fallbackExt.startsWith('.') ? fallbackExt : `.${fallbackExt}`}`;
  }
  return cleaned;
}

/**
 * Validates that a Strapi Media Library asset matches the configured extension and MIME allow-list.
 */
export function isAllowedDownloadAsset(
  ext: unknown,
  mime: unknown,
  allowedExtensions: string[] = DEFAULT_ALLOWED_DOWNLOAD_EXTENSIONS,
  allowedMimeTypes: string[] = DEFAULT_ALLOWED_DOWNLOAD_MIME_TYPES
): boolean {
  const normalizedExt =
    typeof ext === 'string' && ext.trim()
      ? (ext.trim().startsWith('.') ? ext.trim() : `.${ext.trim()}`).toLowerCase()
      : '';
  const normalizedMime =
    typeof mime === 'string' ? mime.trim().toLowerCase() : '';

  const extAllowed =
    normalizedExt.length > 0 &&
    allowedExtensions.some((item) => item.toLowerCase() === normalizedExt);
  const mimeAllowed =
    normalizedMime.length > 0 &&
    allowedMimeTypes.some((item) => item.toLowerCase() === normalizedMime);

  return extAllowed && mimeAllowed;
}

/**
 * Builds hardened HTTP headers for downloadable digital library publications.
 */
export function buildAttachmentHeaders(
  fileName: string,
  mime = 'application/pdf'
): Record<string, string> {
  const safeName = sanitizeFilename(fileName);
  const safeMime =
    typeof mime === 'string' && /^[a-z0-9.+-]+\/[a-z0-9.+-]+$/i.test(mime.trim())
      ? mime.trim()
      : 'application/octet-stream';

  return {
    'Content-Disposition': `attachment; filename="${safeName}"`,
    'X-Content-Type-Options': 'nosniff',
    'Content-Type': safeMime,
    'Cache-Control': 'private, no-store',
  };
}

/**
 * Optimizes Cloudinary URLs generated by `@strapi/provider-upload-cloudinary`
 * with `f_auto,q_auto` and optional width transformations.
 */
export function optimizeCloudinaryMediaUrl(
  rawUrl: unknown,
  enableOptimization = true,
  width?: number
): string {
  if (typeof rawUrl !== 'string' || !rawUrl.trim()) return '';
  const url = rawUrl.trim();
  if (
    !enableOptimization ||
    !url.includes('res.cloudinary.com') ||
    !url.includes('/upload/')
  ) {
    return url;
  }

  const transform =
    typeof width === 'number' && width > 0
      ? `f_auto,q_auto,w_${Math.round(width)}`
      : 'f_auto,q_auto';

  if (url.includes(`/upload/${transform}/`)) {
    return url;
  }
  return url.replace('/upload/', `/upload/${transform}/`);
}

/**
 * Formats Strapi Media Library `size` (stored in KB by `@strapi/upload`) into a human-readable label.
 */
export function formatMediaSizeFromKB(sizeInKB: unknown): string {
  const kb = Number(sizeInKB);
  if (!Number.isFinite(kb) || kb <= 0) return '0 KB';
  if (kb < 1024) {
    return `${Math.max(1, Math.round(kb))} KB`;
  }
  const mb = kb / 1024;
  return `${mb.toFixed(1)} MB`;
}

/**
 * Normalizes a raw `plugin::upload.file` record from Strapi v5 Media Library into `MediaLibraryAsset`.
 */
export function normalizeUploadFile(
  rawFile: unknown,
  enableCloudinaryOptimization = true
): MediaLibraryAsset | null {
  if (!rawFile || typeof rawFile !== 'object') return null;
  const f = rawFile as Record<string, unknown>;
  const rawUrl = typeof f.url === 'string' ? f.url.trim() : '';
  if (!rawUrl) return null;

  const rawFormats =
    f.formats && typeof f.formats === 'object'
      ? (f.formats as Record<string, Record<string, unknown>>)
      : {};
  const formats: Record<string, MediaLibraryFormatVariant> = {};
  for (const [key, variant] of Object.entries(rawFormats)) {
    if (variant && typeof variant.url === 'string' && variant.url.trim()) {
      formats[key] = {
        url: optimizeCloudinaryMediaUrl(
          variant.url,
          enableCloudinaryOptimization
        ),
        width: typeof variant.width === 'number' ? variant.width : undefined,
        height: typeof variant.height === 'number' ? variant.height : undefined,
        mime: typeof variant.mime === 'string' ? variant.mime : undefined,
        sizeInKB: typeof variant.size === 'number' ? variant.size : undefined,
      };
    }
  }

  const sizeInKB = typeof f.size === 'number' && Number.isFinite(f.size) ? f.size : 0;
  const ext = typeof f.ext === 'string' ? f.ext : '';
  const name = sanitizeFilename(f.name || rawUrl, ext || '.bin');
  const optimizedUrl = optimizeCloudinaryMediaUrl(
    rawUrl,
    enableCloudinaryOptimization
  );
  const thumbnailUrl =
    formats.medium?.url ||
    formats.small?.url ||
    formats.thumbnail?.url ||
    optimizeCloudinaryMediaUrl(rawUrl, enableCloudinaryOptimization, 640);

  return {
    id: typeof f.id === 'number' || typeof f.id === 'string' ? f.id : undefined,
    documentId: typeof f.documentId === 'string' ? f.documentId : undefined,
    name,
    alternativeText:
      typeof f.alternativeText === 'string' && f.alternativeText.trim()
        ? f.alternativeText.trim()
        : name,
    caption: typeof f.caption === 'string' ? f.caption.trim() : '',
    url: rawUrl,
    optimizedUrl,
    thumbnailUrl,
    mime: typeof f.mime === 'string' ? f.mime : 'application/octet-stream',
    ext,
    sizeInKB,
    formattedSize: formatMediaSizeFromKB(sizeInKB),
    width: typeof f.width === 'number' ? f.width : undefined,
    height: typeof f.height === 'number' ? f.height : undefined,
    folderPath: typeof f.folderPath === 'string' ? f.folderPath : undefined,
    formats,
  };
}

/**
 * Computes the normalized alphabetical letter group (`A`..`Z` or `#`) for glossary indexing.
 */
export function computeLetterGroup(term: unknown): string {
  if (typeof term !== 'string' || !term.trim()) return '#';
  const normalized = term
    .trim()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
  const firstChar = normalized.charAt(0).toUpperCase();
  return /^[A-Z]$/.test(firstChar) ? firstChar : '#';
}
